# WAP to take marks from d=student and check the grade of the student

marks = int(input("Enter your marks: "))

if marks >= 90:
    print("Student Got Grade: A")

elif marks >= 80:  
    print("Student Got Grade: B")

elif marks >= 70:
    print("Student Got Grade: C")

elif marks >= 60:
    print("Student Got Grade: D")

else:
    print("Student Got Fail, Paisa Barbad") 

